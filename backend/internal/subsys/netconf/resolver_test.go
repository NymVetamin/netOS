package netconf

import (
	"context"
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

type resolverHandoverRunner struct {
	*backendUnitRunner
	path     string
	failStop bool
	install  bool
	aptSeen  bool
}

func (r *resolverHandoverRunner) Run(ctx context.Context, name string, args ...string) (string, error) {
	if name == "systemctl" && strings.Join(args, " ") == "stop networking.service" {
		// Reproduce dhcpcd's stop hook on Debian: only comments remain.
		if err := os.WriteFile(r.path, []byte("# Generated by dhcpcd\n"), 0644); err != nil {
			return "", err
		}
		if r.failStop {
			return "", errors.New("stop failed after hook")
		}
	}
	if r.install && name == "dpkg-query" {
		return "", errors.New("not installed")
	}
	if name == "apt-get" {
		r.aptSeen = true
		data, err := os.ReadFile(r.path)
		if err != nil || !strings.Contains(string(data), "nameserver 192.0.2.53") {
			return "", errors.New("temporary failure resolving repository")
		}
	}
	return r.backendUnitRunner.Run(ctx, name, args...)
}

func TestFreshTakeoverPreservesDNSForNetworkingPackages(t *testing.T) {
	for _, failStop := range []bool{false, true} {
		t.Run(map[bool]string{false: "success", true: "failed handover"}[failStop], func(t *testing.T) {
			useTemporaryPaths(t)
			original := "# DHCP DNS\nsearch example.test\nnameserver 192.0.2.53\noptions edns0\n"
			if err := os.WriteFile(systemResolverPath, []byte(original), 0644); err != nil {
				t.Fatal(err)
			}
			r := &resolverHandoverRunner{backendUnitRunner: newBackendUnitRunner(), path: systemResolverPath, failStop: failStop}
			r.active["networking.service"] = true
			r.enabled["networking.service"] = true
			s := New(r, nil)
			cfg := routerConfig()
			cfg.System.NetworkBackend = "netos"
			err := s.Apply(context.Background(), cfg)
			if (err != nil) != failStop {
				t.Fatalf("takeover err=%v", err)
			}
			data, err := os.ReadFile(systemResolverPath)
			if err != nil || string(data) != original {
				t.Fatalf("lost DNS: %q, %v", data, err)
			}
			if failStop {
				return
			}
			r.install = true
			cfg.System.NetworkBackend = "ifupdown"
			if err := s.Apply(context.Background(), cfg); err != nil {
				t.Fatal(err)
			}
			if !r.aptSeen {
				t.Fatal("package installation was not exercised")
			}
		})
	}
}

func TestPreserveSystemResolverOwnership(t *testing.T) {
	for _, tc := range []struct {
		name, before, after, want string
		remove                    bool
	}{
		{"empty hook output", "nameserver 192.0.2.53\n", "# dhcpcd\n", "nameserver 192.0.2.53\n", false},
		{"removed by hook", "nameserver 192.0.2.53\n", "", "nameserver 192.0.2.53\n", true},
		{"new DNS", "nameserver 192.0.2.53\n", "nameserver 198.51.100.53\n", "nameserver 198.51.100.53\n", false},
		{"local provider", "nameserver 127.0.0.1\n", "", "nameserver 127.0.0.1\n", false},
		{"IPv6", "nameserver fe80::53%eth0\n", "", "nameserver fe80::53%eth0\n", false},
		{"already empty", "# no DNS\n", "", "", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "resolv.conf")
			if err := os.WriteFile(path, []byte(tc.before), 0644); err != nil {
				t.Fatal(err)
			}
			restore, err := preserveSystemResolver(path)
			if err != nil {
				t.Fatal(err)
			}
			if tc.remove {
				err = os.Remove(path)
			} else {
				err = os.WriteFile(path, []byte(tc.after), 0644)
			}
			if err != nil {
				t.Fatal(err)
			}
			if err := restore(); err != nil {
				t.Fatal(err)
			}
			data, err := os.ReadFile(path)
			if err != nil || string(data) != tc.want {
				t.Fatalf("DNS=%q err=%v want=%q", data, err, tc.want)
			}
		})
	}
}

func TestPreserveResolverSymlink(t *testing.T) {
	dir := t.TempDir()
	path, target := filepath.Join(dir, "resolv.conf"), filepath.Join(dir, "runtime.conf")
	if err := os.WriteFile(target, []byte("nameserver 192.0.2.53\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("runtime.conf", path); err != nil {
		t.Fatal(err)
	}
	restore, err := preserveSystemResolver(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, nil, 0644); err != nil {
		t.Fatal(err)
	}
	if err := restore(); err != nil {
		t.Fatal(err)
	}
	if link, err := os.Readlink(path); err != nil || link != "runtime.conf" {
		t.Fatalf("lost symlink: %q %v", link, err)
	}
	if data, err := os.ReadFile(path); err != nil || string(data) != "nameserver 192.0.2.53\n" {
		t.Fatalf("DNS=%q %v", data, err)
	}
}

func TestPreserveResolverDoesNotReplaceNewOwnerSymlink(t *testing.T) {
	dir := t.TempDir()
	path, target := filepath.Join(dir, "resolv.conf"), filepath.Join(dir, "new-owner.conf")
	if err := os.WriteFile(path, []byte("nameserver 192.0.2.53\n"), 0644); err != nil {
		t.Fatal(err)
	}
	restore, err := preserveSystemResolver(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, nil, 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(path); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("new-owner.conf", path); err != nil {
		t.Fatal(err)
	}
	if err := restore(); err != nil {
		t.Fatal(err)
	}
	if link, err := os.Readlink(path); err != nil || link != "new-owner.conf" {
		t.Fatalf("replaced new owner: %q %v", link, err)
	}
	if data, err := os.ReadFile(target); err != nil || len(data) != 0 {
		t.Fatalf("overwrote new owner's data: %q %v", data, err)
	}
}
