const IPTVUnit = "netos-iptv.service"
const iptvOwner = "# Generated by netOS: IPTV\n"

type IPTV struct {
	Runner                     system.Runner
	StateDir, UnitDir, VIFPath string
	links                      func(*config.Config) (string, error)
}

func NewIPTV(r system.Runner, stateDir string) *IPTV {
	return &IPTV{r, stateDir, "/etc/systemd/system", "/proc/net/ip_mr_vif", iptvLinks}
}
func (s *IPTV) Name() string { return "iptv" }
func (s *IPTV) paths() (string, string) {
	return filepath.Join(s.StateDir, "iptv.conf"), filepath.Join(s.UnitDir, IPTVUnit)
}

func RenderIPTV(c *config.Config) []byte {
	if !c.IPTV.Enabled {
		return nil
	}
	var b strings.Builder
	b.WriteString(iptvOwner)
	// No quickleave: another viewer may still use the same group.
	fmt.Fprintf(&b, "phyint %s upstream ratelimit 0 threshold 1\n", c.IPTVUpstream())
	for _, source := range c.IPTV.SourceNetworks() {
		fmt.Fprintf(&b, " altnet %s\n", source)
	}
	for _, w := range c.WANs {
		if w.ID == c.IPTV.Upstream {
			fmt.Fprintf(&b, "# address %s %s\n", w.Proto, w.Address)
		}
	}
	for _, n := range c.IPTVNetworks() {
		fmt.Fprintf(&b, "phyint %s downstream ratelimit 0 threshold 1\n# address %s\n", c.InterfaceName(n.Interface), n.RouterAddress)
	}
	return []byte(b.String())
}

func (s *IPTV) unit() []byte {
	conf, _ := s.paths()
	return []byte(iptvOwner + `[Unit]
Description=netOS IPTV multicast proxy
After=network.target
StartLimitIntervalSec=0
[Service]
Type=simple
ExecStart=/usr/sbin/igmpproxy -d ` + conf + `
Restart=on-failure
RestartSec=5
NoNewPrivileges=true
ProtectHome=true
ProtectSystem=strict
PrivateTmp=true
CapabilityBoundingSet=CAP_NET_ADMIN CAP_NET_RAW
`)
}

func (s *IPTV) Plan(old, next *config.Config) ([]apply.Action, error) {
	if !next.IPTV.Enabled && (old == nil || !old.IPTV.Enabled) {
		return nil, nil
	}
	conf, unit := s.paths()
	if old == nil || string(RenderIPTV(old)) != string(RenderIPTV(next)) || (next.IPTV.Enabled && (system.FileChanged(conf, RenderIPTV(next)) || system.FileChanged(unit, s.unit()))) {
		return []apply.Action{{Subsystem: s.Name(), Kind: "update", Target: "IPTV", Detail: "аплинк, сети зрителей и источники", Disruptive: true, Confirmation: apply.ConfirmationSafe}}, nil
	}
	return nil, nil
}

func (s *IPTV) owned() (bool, error) {
	_, unit := s.paths()
	b, err := os.ReadFile(unit)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !strings.HasPrefix(string(b), iptvOwner) {
		return false, fmt.Errorf("служба %s не принадлежит netOS", IPTVUnit)
	}
	return true, nil
}

// Stop changed scopes before removing interfaces, packages or firewall rules.
// netosd starts the proxy after its firewall, including at boot.
type IPTVPreparation struct{ S *IPTV }

func (p *IPTVPreparation) Name() string                                     { return "iptv-prepare" }
func (p *IPTVPreparation) Plan(a, b *config.Config) ([]apply.Action, error) { return nil, nil }
func (p *IPTVPreparation) Health(context.Context, *config.Config) error     { return nil }
func (p *IPTVPreparation) Apply(ctx context.Context, c *config.Config) error {
	owned, err := p.S.owned()
	if err != nil || !owned {
		return err
	}
	conf, _ := p.S.paths()
	if !c.IPTV.Enabled || system.FileChanged(conf, RenderIPTV(c)) {
		_, err = p.S.Runner.Run(ctx, "systemctl", "stop", IPTVUnit)
	}
	return err
}

func (s *IPTV) Apply(ctx context.Context, c *config.Config) error {
	owned, err := s.owned()
	if err != nil {
		return err
	}
	conf, unit := s.paths()
	if !c.IPTV.Enabled {
		if !owned {
			return nil
		}
		if _, err = s.Runner.Run(ctx, "systemctl", "stop", IPTVUnit); err != nil {
			return err
		}
		for _, path := range []string{conf, unit, filepath.Join(s.StateDir, "iptv.links")} {
			if err = os.Remove(path); err != nil && !os.IsNotExist(err) {
				return err
			}
		}
		_, err = s.Runner.Run(ctx, "systemctl", "daemon-reload")
		return err
	}
	state, err := s.links(c)
	if err != nil {
		return err
	}
	data := RenderIPTV(c)
	unitData := s.unit()
	changed := system.FileChanged(conf, data) || system.FileChanged(unit, unitData) || system.FileChanged(filepath.Join(s.StateDir, "iptv.links"), []byte(state))
	for path, content := range map[string][]byte{conf: data, unit: unitData} {
		if _, err = system.WriteFileAtomicIfChanged(path, content, 0644); err != nil {
			return err
		}
	}
	if changed {
		if _, err = s.Runner.Run(ctx, "systemctl", "daemon-reload"); err != nil {
			return err
		}
	}
	active, _ := s.Runner.Run(ctx, "systemctl", "is-active", IPTVUnit)
	if changed || strings.TrimSpace(active) != "active" {
		if _, err = s.Runner.Run(ctx, "systemctl", "restart", IPTVUnit); err != nil {
			return err
		}
	}
	// A successful fork isn't proof that the daemon accepted its interfaces.
	deadline := time.NewTimer(3 * time.Second)
	defer deadline.Stop()
	tick := time.NewTicker(50 * time.Millisecond)
	defer tick.Stop()
	for {
		if err = s.Health(ctx, c); err == nil {
			break
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-deadline.C:
			return err
		case <-tick.C:
		}
	}
	_, err = system.WriteFileAtomicIfChanged(filepath.Join(s.StateDir, "iptv.links"), []byte(state), 0600)
	return err
}

func (s *IPTV) Health(ctx context.Context, c *config.Config) error {
	if !c.IPTV.Enabled {
		return nil
	}
	data, err := os.ReadFile(s.VIFPath)
	if err != nil {
		return fmt.Errorf("IPTV: таблица multicast: %w", err)
	}
	wanted := []string{c.IPTVUpstream()}
	for _, n := range c.IPTVNetworks() {
		wanted = append(wanted, c.InterfaceName(n.Interface))
	}
	seen := map[string]bool{}
	for _, line := range strings.Split(string(data), "\n") {
		f := strings.Fields(line)
		if len(f) > 1 {
			seen[f[1]] = true
		}
	}
	for _, name := range wanted {
		if name == "" || !seen[name] {
			return fmt.Errorf("IPTV: интерфейс %s не подключён к multicast-маршрутизации", name)
		}
	}
	active, err := s.Runner.Run(ctx, "systemctl", "is-active", IPTVUnit)
	if err != nil || strings.TrimSpace(active) != "active" {
		return fmt.Errorf("IPTV: служба не работает")
	}
	return nil
}

func iptvLinks(c *config.Config) (string, error) {
	wanted := []string{c.IPTVUpstream()}
	for _, n := range c.IPTVNetworks() {
		wanted = append(wanted, c.InterfaceName(n.Interface))
	}
	sort.Strings(wanted)
	var rows []string
	for _, name := range wanted {
		iface, err := net.InterfaceByName(name)
		if err != nil {
			return "", fmt.Errorf("IPTV: интерфейс %s: %w", name, err)
		}
		if iface.Flags&net.FlagUp == 0 || iface.Flags&net.FlagMulticast == 0 {
			return "", fmt.Errorf("IPTV: интерфейс %s не готов к multicast", name)
		}
		addresses, err := iface.Addrs()
		if err != nil {
			return "", err
		}
		var ipv4 []string
		for _, a := range addresses {
			ip, _, err := net.ParseCIDR(a.String())
			if err == nil && ip.To4() != nil {
				ipv4 = append(ipv4, a.String())
			}
		}
		if len(ipv4) == 0 {
			return "", fmt.Errorf("IPTV: интерфейс %s ещё не получил IPv4-адрес", name)
		}
		sort.Strings(ipv4)
		rows = append(rows, fmt.Sprintf("%s %d %s", name, iface.Index, strings.Join(ipv4, ",")))
	}
	return strings.Join(rows, "\n"), nil
}
